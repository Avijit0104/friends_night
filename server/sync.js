#!/usr/bin/env node
/* Friend's Night — keeps the server in line with hub/games.json.
 *
 * Runs every 2 minutes (systemd timer, see setup.sh) and can be run by hand: `node server/sync.js`.
 *  1. Pulls the latest Friend's Night repo (this repo: the hub page + these scripts).
 *  2. For every game in hub/games.json with a `repo` and a `port`:
 *       new game      → clone it, npm install, start it under pm2
 *       new commits   → pull, npm install, restart only that game
 *                       (waits up to 30 min while that game reports open rooms, so nobody's game is cut off)
 *  3. Games removed from games.json are stopped.
 *  4. Rewrites the Caddy config (hub + one subdomain per game + /status/<id> checks) and reloads Caddy if it changed.
 *
 * Nothing here needs root. Paths come from /opt/friendsnight/site.env (written by setup.sh).
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = process.env.FN_ROOT || '/opt/friendsnight';
const APP = path.join(ROOT, 'app');       // clone of this repo
const GAMES = path.join(ROOT, 'games');   // one folder per game
const CADDY_OUT = path.join(ROOT, 'Caddyfile');
const PM2_OUT = path.join(ROOT, 'ecosystem.config.js');
const STATE = path.join(ROOT, 'state.json');

const log = (...a) => console.log(new Date().toISOString(), ...a);
const run = (cmd, args, opts = {}) => execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], ...opts }).trim();
const git = (dir, ...args) => run('git', ['-C', dir, ...args]);

function readEnv() {
  const env = {};
  const file = path.join(ROOT, 'site.env');
  if (!fs.existsSync(file)) throw new Error(`${file} is missing. Run setup.sh first.`);
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z_]+)\s*=\s*"?([^"]*)"?\s*$/);
    if (m) env[m[1]] = m[2];
  }
  if (!env.DOMAIN) throw new Error('DOMAIN is not set in site.env');
  return env;
}

// Fetch a repo; returns the new commit id, or null when there's nothing new.
function fetchNew(dir, branch) {
  git(dir, 'fetch', '--quiet', '--depth', '1', 'origin', branch);
  const after = git(dir, 'rev-parse', 'FETCH_HEAD');
  return after === git(dir, 'rev-parse', 'HEAD') ? null : after;
}
const apply = (dir, sha) => git(dir, 'reset', '--quiet', '--hard', sha);

// Is somebody playing right now? Games whose health check answers JSON like {"rooms": 2} tell us;
// for the others we can't know, so they update straight away.
function busy(g) {
  try {
    const out = run('curl', ['-s', '--max-time', '3', `http://127.0.0.1:${g.port}${g.health || '/'}`]);
    const j = JSON.parse(out);
    return Number(j.rooms || j.roomsOpen || 0) > 0;
  } catch { return false; }
}
const MAX_WAIT_MS = 30 * 60 * 1000; // never hold an update back longer than this

function install(dir) {
  const hasLock = fs.existsSync(path.join(dir, 'package-lock.json'));
  try {
    run('npm', [hasLock ? 'ci' : 'install', '--omit=dev', '--no-audit', '--no-fund'], { cwd: dir, timeout: 600000 });
  } catch (e) {
    if (!hasLock) throw e;
    log(`  npm ci failed in ${path.basename(dir)}, trying npm install`);
    run('npm', ['install', '--omit=dev', '--no-audit', '--no-fund'], { cwd: dir, timeout: 600000 });
  }
}

// pm2 runs `node <file>` directly when the start script is that simple (cleaner restarts than going through npm).
function startCommand(dir) {
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const start = (pkg.scripts && pkg.scripts.start) || `node ${pkg.main || 'server.js'}`;
  const m = start.match(/^node\s+(\S+)$/);
  return m ? { script: m[1] } : { script: 'npm', args: 'start' };
}

function validGame(g) {
  return g && /^[a-z0-9-]+$/.test(g.id || '') && g.repo && Number.isInteger(g.port) && g.port > 1024 && g.port < 65536 &&
    /^[a-z0-9-]+$/.test(g.subdomain || '');
}

function caddyfile(env, games) {
  const hubDir = path.join(APP, 'hub');
  const status = games.map((g) => `
	handle /status/${g.id} {
		rewrite * ${g.health || '/'}
		reverse_proxy 127.0.0.1:${g.port}
		header Cache-Control "no-store"
	}`).join('');
  const sites = games.map((g) => `
# ${g.name}
${g.subdomain}.${env.DOMAIN} {
	encode zstd gzip
	reverse_proxy 127.0.0.1:${g.port}
}
`).join('');
  return `# Generated by server/sync.js from hub/games.json. Do not edit by hand: your changes will be overwritten.

# Friend's Night hub
${env.DOMAIN} {
	encode zstd gzip
	header {
		X-Content-Type-Options nosniff
		Referrer-Policy strict-origin-when-cross-origin
	}
	@fresh path / /index.html /games.json /sw.js /app.js /style.css
	header @fresh Cache-Control "no-cache"
${status}
	handle {
		root * ${hubDir}
		file_server
	}
}
${sites}`;
}

function pm2Config(games) {
  const apps = games.map((g) => ({
    name: g.id,
    cwd: path.join(GAMES, g.id),
    ...startCommand(path.join(GAMES, g.id)),
    env: { NODE_ENV: 'production', PORT: String(g.port) },
    max_memory_restart: g.maxMemory || '400M',   // a leaking game restarts itself instead of slowing the others down
    exp_backoff_restart_delay: 1000,              // crash loop? wait longer between restarts
    time: true,
  }));
  return `// Generated by server/sync.js from hub/games.json.\nmodule.exports = ${JSON.stringify({ apps }, null, 2)};\n`;
}

function writeIfChanged(file, text) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text) return false;
  fs.writeFileSync(file, text);
  return true;
}

function main() {
  const env = readEnv();
  fs.mkdirSync(GAMES, { recursive: true });
  const state = { games: [], waiting: {}, ...(fs.existsSync(STATE) ? JSON.parse(fs.readFileSync(STATE, 'utf8')) : {}) };
  const waiting = {};

  // 1. this repo
  try {
    const sha = fetchNew(APP, env.BRANCH || 'main');
    if (sha) { apply(APP, sha); log('Friend\'s Night repo updated'); }
  } catch (e) { log('Could not update the Friend\'s Night repo:', e.message.split('\n')[0]); }

  // 2. games
  const list = JSON.parse(fs.readFileSync(path.join(APP, 'hub', 'games.json'), 'utf8')).games.filter((g) => g.repo && g.port);
  const games = [];
  const restart = [];
  const ports = new Set();
  for (const g of list) {
    if (!validGame(g)) { log(`Skipping "${g.id}": needs a lowercase id, a subdomain, a repo and a port above 1024`); continue; }
    if (ports.has(g.port)) { log(`Skipping "${g.id}": port ${g.port} is already used by another game`); continue; }
    ports.add(g.port);
    const dir = path.join(GAMES, g.id);
    const branch = g.branch || 'main';
    try {
      if (!fs.existsSync(path.join(dir, '.git'))) {
        log(`New game: cloning ${g.name}`);
        try {
          run('git', ['clone', '--quiet', '--depth', '1', '--branch', branch, g.repo, dir]);
          install(dir);
        } catch (e) {
          fs.rmSync(dir, { recursive: true, force: true }); // half-installed: start clean next time
          throw e;
        }
      } else {
        const sha = fetchNew(dir, branch);
        if (sha) {
          const since = state.waiting[g.id] || Date.now();
          if (busy(g) && Date.now() - since < MAX_WAIT_MS) {
            if (!state.waiting[g.id]) log(`Update for ${g.name} is waiting: people are playing right now`);
            waiting[g.id] = since;
          } else {
            log(`Update for ${g.name}: installing and restarting`);
            apply(dir, sha);
            install(dir);
            restart.push(g.id);
          }
        }
      }
      games.push(g);
    } catch (e) {
      log(`Problem with ${g.name}:`, e.message.split('\n')[0]);
      if (fs.existsSync(path.join(dir, 'package.json'))) games.push(g); // keep running the old version
    }
  }

  // 3. pm2: start new games, restart only the updated ones, stop removed ones.
  //    Games that didn't change are never touched, so rooms in progress there keep going.
  writeIfChanged(PM2_OUT, pm2Config(games));
  const running = new Set(JSON.parse(run('pm2', ['jlist']) || '[]').map((p) => p.name));
  let changed = false;
  for (const g of games) {
    if (!running.has(g.id)) { log(`Starting ${g.name} on port ${g.port}`); run('pm2', ['start', PM2_OUT, '--only', g.id]); changed = true; }
    else if (restart.includes(g.id)) { run('pm2', ['restart', PM2_OUT, '--only', g.id, '--update-env']); changed = true; }
  }
  for (const id of state.games) {
    if (!games.some((g) => g.id === id) && running.has(id)) {
      log(`Removed game: stopping ${id}`);
      run('pm2', ['delete', id]); changed = true;
    }
  }
  if (changed) run('pm2', ['save', '--force']);

  // 4. Caddy
  if (writeIfChanged(CADDY_OUT, caddyfile(env, games))) {
    log('Caddy config changed: reloading');
    run('caddy', ['reload', '--config', '/etc/caddy/Caddyfile', '--adapter', 'caddyfile']);
  }

  fs.writeFileSync(STATE, JSON.stringify({ games: games.map((g) => g.id), waiting, at: new Date().toISOString() }));
}

try { main(); } catch (e) { log('sync failed:', e.message); process.exitCode = 1; }
